# ---------------------------------------------------------------- CSS
def decl(p):
    skip = {'page', 'page-stops'}
    return ' '.join('--%s:%s;' % (k, v) for k, v in p.items() if k not in skip) + ' --page:%s;' % p['page']
def inkdecl(t): return '--ink:%s; --ink-2:%s; --muted:%s;' % t
def hldecl(h):
    f, t = h['fill'], h['text']
    return ('--hl-fill:linear-gradient(118deg,%s 0%%,%s 55%%,%s 100%%); --hl-fill-v:linear-gradient(0deg,%s,%s); '
            '--hl-text:linear-gradient(100deg,%s 0%%,%s 50%%,%s 100%%); --hl-label:%s; --hl-glow:%s;') % (f[0], f[1], f[2], f[0], f[2], t[0], t[1], t[2], h['label'], h['glow'])

