# ---------------------------------------------------------------- contrast
def lum(h):
    h = h.lstrip('#'); r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True); return (la + 0.05) / (lb + 0.05)

fails, worst = [], {}
def need(tag, fg, bg, n=4.5):
    r = ratio(fg, bg)
    worst[tag] = min(worst.get(tag, 99), r)
    if r < n: fails.append('%s: %s on %s = %.2f (need %.1f)' % (tag, fg, bg, r, n))

for style, P in (('classic', CLASSIC), ('colourful', COLOURFUL)):
    for mode in ('light', 'dark'):
        p = P[mode]
        bgs = [p['ground'], p['surface'], p['surface-2']] + p.get('page-stops', [])
        inks = [('default', (p['ink'], p['ink-2'], p['muted']))] + [(k, v[0 if mode == 'light' else 1]) for k, v in INKS.items()]
        for name, (ink, ink2, muted) in inks:
            for bg in bgs:
                need('%s %s text %s' % (style, mode, name), ink, bg, 7)
                need('%s %s text-2 %s' % (style, mode, name), ink2, bg)
                need('%s %s muted %s' % (style, mode, name), muted, bg)
        if style == 'colourful':
            for bg in (p['surface'], p['surface-2']):
                need('%s %s headings' % (style, mode), p['head'], bg)
                need('%s %s accent as text' % (style, mode), p['accent'], bg)
            need('%s %s text on accent' % (style, mode), p['accent-ink'], p['accent'])
            H = HIGHLIGHT[mode]
            for i, c in enumerate(H['fill']):  # big number sits on the first stops (large text, 3:1); the caption on the last two (4.5:1)
                need('%s %s white on highlight fill' % (style, mode), '#FFFFFF', c, 4.5 if i else 3)
            for c in H['text']:
                for bg in (p['surface'], p['surface-2']): need('%s %s highlight score number (large)' % (style, mode), c, bg, 3)
            for bg in (p['surface'], p['surface-2']): need('%s %s highlight label' % (style, mode), H['label'], bg)
            for k in ('done', 'mod', 'skip', 'miss', 'k-strength', 'k-hyrox', 'k-long', 'k-rest', 'k-race', 'test', 'sim'):
                need('%s %s %s on its tint' % (style, mode, k), p[k], p[k + '-tint'])
